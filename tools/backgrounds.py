"""Built-in background images, shared by the web page and the Mac app.

All are public domain on Wikimedia Commons (paintings old enough to be out of
copyright, and photos made by NASA or the US National Park Service), checked
with the Commons API when added. They're loaded straight from
upload.wikimedia.org at a standard thumbnail size (500, 1920 or 3840 wide:
Wikimedia refuses other sizes).

Run `python3 tools/backgrounds.py` after editing to regenerate:
  web/backgrounds.js and apple/Kay2Do/Backgrounds.swift
"""
import hashlib, json, pathlib, urllib.parse

# id, Commons file name, original width, title, credit
IMAGES = [
    ("great-wave", "Tsunami by hokusai 19th century.jpg", 3859, "The Great Wave off Kanagawa", "Katsushika Hokusai, c. 1831"),
    ("red-fuji", "Red Fuji southern wind clear morning.jpg", 4400, "Fine Wind, Clear Morning (Red Fuji)", "Katsushika Hokusai, c. 1831"),
    ("starry-night", "Van Gogh - Starry Night - Google Art Project.jpg", 44567, "The Starry Night", "Vincent van Gogh, 1889"),
    ("impression", "Claude Monet, Impression, soleil levant.jpg", 1600, "Impression, Sunrise", "Claude Monet, 1872"),
    ("water-lilies", "Claude Monet - Water Lilies - 1906, Ryerson.jpg", 2342, "Water Lilies", "Claude Monet, 1906"),
    ("parasol", "Claude Monet - Woman with a Parasol - Madame Monet and Her Son - Google Art Project.jpg", 6001, "Woman with a Parasol", "Claude Monet, 1875"),
    ("wanderer", "Caspar David Friedrich - Wanderer above the sea of fog.jpg", 2327, "Wanderer above the Sea of Fog", "Caspar David Friedrich, c. 1818"),
    ("ninth-wave", "Aivazovsky, Ivan - The Ninth Wave.jpg", 5815, "The Ninth Wave", "Ivan Aivazovsky, 1850"),
    ("sierra", "Albert Bierstadt - Among the Sierra Nevada, California - Google Art Project.jpg", 3993, "Among the Sierra Nevada, California", "Albert Bierstadt, 1868"),
    ("yellowstone", "Thomas Moran - Grand Canyon of the Yellowstone - Smithsonian.jpg", 4000, "Grand Canyon of the Yellowstone", "Thomas Moran, 1872"),
    ("tetons", "Adams The Tetons and the Snake River.jpg", 3000, "The Tetons and the Snake River", "Ansel Adams, 1942, National Park Service"),
    ("earth", "The Earth seen from Apollo 17.jpg", 3000, "The Blue Marble", "NASA, Apollo 17, 1972"),
    ("pillars", "Pillars of creation 2014 HST WFC3-UVIS full-res denoised.jpg", 6780, "Pillars of Creation", "NASA, ESA and the Hubble Heritage Team, 2014"),
    ("deep-field", "Hubble ultra deep field.jpg", 3100, "Hubble Ultra Deep Field", "NASA, ESA and the Hubble Space Telescope, 2004"),
]

def commons_url(name, width, original):
    n = name.replace(" ", "_")
    h = hashlib.md5(n.encode()).hexdigest()
    q = urllib.parse.quote(n)
    if width is None or width >= original:
        return f"https://upload.wikimedia.org/wikipedia/commons/{h[0]}/{h[:2]}/{q}"
    return f"https://upload.wikimedia.org/wikipedia/commons/thumb/{h[0]}/{h[:2]}/{q}/{width}px-{q}"

rows = []
for id_, name, width, title, credit in IMAGES:
    full = 3840 if width > 3840 else (1920 if width > 1920 else None)
    rows.append({
        "id": id_, "title": title, "credit": credit,
        "full": commons_url(name, full, width),
        "thumb": commons_url(name, 500, width),
        "page": "https://commons.wikimedia.org/wiki/File:" + urllib.parse.quote(name.replace(" ", "_")),
    })

root = pathlib.Path(__file__).resolve().parent.parent
(root / "web/backgrounds.js").write_text(
    "// Generated by tools/backgrounds.py. Edit that file, not this one.\nwindow.KAY2DO_BACKGROUNDS = "
    + json.dumps(rows, ensure_ascii=False, indent=1) + ";\n")
lines = ["// Generated by tools/backgrounds.py. Edit that file, not this one.", "",
         "enum Backgrounds {", "    static let all: [BackgroundPhoto] = ["]
for r in rows:
    args = ", ".join(f"{k}: {json.dumps(r[k], ensure_ascii=False)}" for k in ("id", "title", "credit", "full", "thumb", "page"))
    lines.append(f"        BackgroundPhoto({args}),")
lines += ["    ]", "}", ""]
(root / "apple/Kay2Do/Backgrounds.swift").write_text("\n".join(lines))
print(len(rows), "backgrounds")
